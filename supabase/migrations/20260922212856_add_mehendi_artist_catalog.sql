create table if not exists public.mehendi_artists (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 120),
  public_address text not null check (char_length(public_address) between 2 and 240),
  base_area text not null check (char_length(base_area) between 2 and 120),
  bio text check (bio is null or char_length(bio) <= 1200),
  photo_url text,
  photo_path text,
  active boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mehendi_catalog_items (
  id uuid primary key default gen_random_uuid(),
  artist_id uuid not null references public.mehendi_artists(id) on delete restrict,
  title text not null check (char_length(title) between 2 and 160),
  service_type text not null check (service_type in ('Mehendi','Kolka','Mehendi + Kolka')),
  description text check (description is null or char_length(description) <= 1600),
  price numeric(12,2) not null check (price >= 0),
  pricing_unit text not null default 'per_booking' check (pricing_unit in ('per_booking','per_person')),
  duration_minutes integer check (duration_minutes is null or duration_minutes between 15 and 1440),
  image_url text,
  image_path text,
  active boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mehendi_travel_zones (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(label) between 2 and 80),
  min_km numeric(6,2) not null check (min_km >= 0),
  max_km numeric(6,2) not null check (max_km > min_km and max_km <= 15),
  fee numeric(12,2) not null check (fee >= 0),
  active boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mehendi_addons (
  id uuid primary key default gen_random_uuid(),
