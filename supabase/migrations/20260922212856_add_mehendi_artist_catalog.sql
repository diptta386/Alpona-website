create or replace function public.update_mehendi_booking_status(p_booking_id bigint,p_status text)
returns jsonb language plpgsql set search_path to '' as $function$
declare v_booking public.mehendi_bookings%rowtype; v_slot_key text;
begin
  if p_status not in ('Request Received','Contacted','Confirmed','Completed','Cancelled','Slot Unavailable') then
    raise exception using errcode='P0001',message='INVALID_BOOKING_STATUS';
  end if;
  select * into v_booking from public.mehendi_bookings where id=p_booking_id for update;
  if not found then raise exception using errcode='P0001',message='BOOKING_NOT_FOUND'; end if;
  if v_booking.payment_status='paid' and p_status='Cancelled' then
    raise exception using errcode='P0001',message='PAID_BOOKING_NON_CANCELLABLE';
  end if;
  v_slot_key:=v_booking.event_date::text||'|'||v_booking.preferred_time;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_slot_key,0));
  if p_status='Confirmed' then
    if exists(select 1 from public.mehendi_bookings where event_date=v_booking.event_date and preferred_time=v_booking.preferred_time and status in ('Confirmed','Completed') and id<>p_booking_id) then
      raise exception using errcode='P0001',message='SLOT_ALREADY_BOOKED';
    end if;
    update public.mehendi_bookings set status='Confirmed',updated_at=now() where id=p_booking_id;
    update public.mehendi_bookings set status='Slot Unavailable',updated_at=now() where event_date=v_booking.event_date and preferred_time=v_booking.preferred_time and id<>p_booking_id and status in ('Request Received','Contacted');
  else
    update public.mehendi_bookings set status=p_status,updated_at=now() where id=p_booking_id;
    if v_booking.status in ('Confirmed','Completed') and p_status not in ('Confirmed','Completed') then
      update public.mehendi_bookings set status='Request Received',updated_at=now() where event_date=v_booking.event_date and preferred_time=v_booking.preferred_time and status='Slot Unavailable';
    end if;
  end if;
  select * into v_booking from public.mehendi_bookings where id=p_booking_id;
  return to_jsonb(v_booking);
end;$function$;
