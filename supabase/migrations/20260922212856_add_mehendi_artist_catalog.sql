create or replace function public.create_secure_mehendi_booking(p_booking jsonb)
returns jsonb language plpgsql set search_path to '' as $function$
declare
  v_id bigint; v_existing_id bigint; v_existing_booking_number text; v_paths text[];
  v_event_date date := (p_booking->>'event_date')::date;
  v_preferred_time text := p_booking->>'preferred_time';
  v_client_request_id uuid := nullif(p_booking->>'client_request_id','')::uuid;
begin
  if v_event_date < current_date then raise exception using errcode='P0001',message='EVENT_DATE_IN_PAST'; end if;
  if v_preferred_time not in ('Morning','Afternoon','Evening','Night') then raise exception using errcode='P0001',message='INVALID_TIME_SLOT'; end if;
  if v_client_request_id is not null then
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('mehendi-request|'||v_client_request_id::text,0));
    select id,booking_number into v_existing_id,v_existing_booking_number from public.mehendi_bookings where client_request_id=v_client_request_id limit 1;
    if v_existing_id is not null then return jsonb_build_object('id',v_existing_id,'booking_number',v_existing_booking_number,'reused',true); end if;
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_event_date::text||'|'||v_preferred_time,0));
  if exists(select 1 from public.mehendi_bookings where event_date=v_event_date and preferred_time=v_preferred_time and status in ('Confirmed','Completed')) then
    raise exception using errcode='P0001',message='SLOT_ALREADY_BOOKED';
  end if;
  select coalesce(array_agg(value),'{}'::text[]) into v_paths from jsonb_array_elements_text(coalesce(p_booking->'custom_design_paths','[]'::jsonb));
  insert into public.mehendi_bookings(
    booking_number,client_request_id,customer_name,phone,customer_email,event_date,preferred_time,occasion,service_type,number_of_people,
    venue_area,address,notes,mehendi_coverage,mehendi_side,mehendi_hands,kolka_placement,kolka_side,custom_design_paths,status,
    artist_id,catalog_item_id,travel_zone_id,addon_id,addon_quantity,artist_name_snapshot,catalog_item_snapshot,travel_zone_snapshot,addon_snapshot,
    catalog_base_price,catalog_travel_fee,catalog_addon_price,catalog_total,catalog_pricing_unit,cancellation_acknowledged,payment_status
  ) values (
    p_booking->>'booking_number',v_client_request_id,p_booking->>'customer_name',p_booking->>'phone',nullif(p_booking->>'customer_email',''),v_event_date,v_preferred_time,
    p_booking->>'occasion',p_booking->>'service_type',(p_booking->>'number_of_people')::integer,p_booking->>'venue_area',p_booking->>'address',nullif(p_booking->>'notes',''),
    nullif(p_booking->>'mehendi_coverage',''),nullif(p_booking->>'mehendi_side',''),nullif(p_booking->>'mehendi_hands',''),nullif(p_booking->>'kolka_placement',''),
    nullif(p_booking->>'kolka_side',''),v_paths,'Request Received',nullif(p_booking->>'artist_id','')::uuid,nullif(p_booking->>'catalog_item_id','')::uuid,
    nullif(p_booking->>'travel_zone_id','')::bigint,nullif(p_booking->>'addon_id','')::uuid,coalesce((p_booking->>'addon_quantity')::integer,0),
    nullif(p_booking->>'artist_name_snapshot',''),nullif(p_booking->>'catalog_item_snapshot',''),nullif(p_booking->>'travel_zone_snapshot',''),nullif(p_booking->>'addon_snapshot',''),
    nullif(p_booking->>'catalog_base_price','')::numeric,nullif(p_booking->>'catalog_travel_fee','')::numeric,nullif(p_booking->>'catalog_addon_price','')::numeric,
    nullif(p_booking->>'catalog_total','')::numeric,nullif(p_booking->>'catalog_pricing_unit',''),coalesce((p_booking->>'cancellation_acknowledged')::boolean,false),'not_requested'
  ) returning id into v_id;
  return jsonb_build_object('id',v_id,'booking_number',p_booking->>'booking_number','reused',false);
end;$function$;

