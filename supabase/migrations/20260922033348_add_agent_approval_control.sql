create table if not exists public.agent_tasks (
  id bigint generated by default as identity primary key,
  agent_role text not null check (agent_role in ('operations','content','design','support','analyst')),
  direction text not null check (char_length(direction) between 3 and 2000),
  risk_level text not null default 'low' check (risk_level in ('low','medium','high')),
  status text not null default 'awaiting_start_approval' check (status in (
    'awaiting_start_approval','approved_to_start','in_progress',
    'awaiting_completion_approval','completed','rejected'
  )),
  result_summary text check (result_summary is null or char_length(result_summary) <= 4000),
  created_by uuid not null references auth.users(id),
  start_approved_by uuid references auth.users(id),
  start_approved_at timestamptz,
  started_at timestamptz,
  completion_requested_at timestamptz,
  completion_approved_by uuid references auth.users(id),
  completion_approved_at timestamptz,
  completed_at timestamptz,
  rejected_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agent_start_approval_required check (
    status in ('awaiting_start_approval','rejected')
    or (start_approved_by is not null and start_approved_at is not null)
  ),
  constraint agent_finish_approval_required check (
    status <> 'completed'
    or (completion_approved_by is not null and completion_approved_at is not null and completed_at is not null)
  )
);

