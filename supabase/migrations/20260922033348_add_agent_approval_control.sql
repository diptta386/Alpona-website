create or replace function public.enforce_agent_task_approval()
returns trigger language plpgsql security invoker set search_path = public, auth as $$
declare
  owner_id constant uuid := '5beecdb3-5e80-4a35-9133-5fc01ab7a772'::uuid;
  caller_id uuid := auth.uid();
  caller_aal text := auth.jwt()->>'aal';
begin
  if caller_id is distinct from owner_id or caller_aal is distinct from 'aal2' then
    raise exception 'Owner two-step approval is required';
  end if;

  if tg_op = 'INSERT' then
    if new.status <> 'awaiting_start_approval' or new.created_by is distinct from caller_id
       or new.start_approved_by is not null or new.completion_approved_by is not null then
      raise exception 'New tasks must wait for owner start approval';
    end if;
    new.updated_at := now();
    return new;
  end if;

  if new.id is distinct from old.id or new.created_by is distinct from old.created_by
     or new.agent_role is distinct from old.agent_role or new.direction is distinct from old.direction
     or new.risk_level is distinct from old.risk_level or new.created_at is distinct from old.created_at then
    raise exception 'Agent task identity and direction are immutable';
  end if;

  if old.status = 'awaiting_start_approval' and new.status = 'approved_to_start' then
    if new.start_approved_by is distinct from caller_id or new.start_approved_at is null then
      raise exception 'Explicit owner start approval is required';
    end if;
  elsif old.status = 'awaiting_start_approval' and new.status = 'rejected' then
    if new.rejected_at is null then raise exception 'Rejection timestamp is required'; end if;
  elsif old.status = 'approved_to_start' and new.status = 'in_progress' then
    if old.start_approved_by is distinct from caller_id or old.start_approved_at is null or new.started_at is null then
      raise exception 'Task cannot start without owner approval';
    end if;
  elsif old.status = 'in_progress' and new.status = 'awaiting_completion_approval' then
    if new.completion_requested_at is null or nullif(btrim(new.result_summary), '') is null then
      raise exception 'Work summary is required before finish approval';
    end if;
  elsif old.status = 'awaiting_completion_approval' and new.status = 'completed' then
    if new.completion_approved_by is distinct from caller_id or new.completion_approved_at is null or new.completed_at is null then
      raise exception 'Explicit owner finish approval is required';
    end if;
  elsif old.status = 'awaiting_completion_approval' and new.status = 'in_progress' then
    if new.completion_requested_at is not null or new.result_summary is not null then
      raise exception 'Returned work must clear its completion request';
    end if;
  elsif new.status is distinct from old.status then
    raise exception 'Invalid agent task status transition: % to %', old.status, new.status;
  end if;

  new.updated_at := now();
  return new;
end;
$$;

revoke all on function public.enforce_agent_task_approval() from public, anon, authenticated;
drop trigger if exists agent_task_approval_guard on public.agent_tasks;
create trigger agent_task_approval_guard before insert or update on public.agent_tasks
for each row execute function public.enforce_agent_task_approval();

comment on table public.agent_tasks is
'Owner-controlled agent queue. Separate start and completion approvals are enforced in the database.';
